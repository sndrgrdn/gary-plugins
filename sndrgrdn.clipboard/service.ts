import { Effect, Schema, Stream, host, topic } from "gary:effect";
import type { Entry } from "./topic";

const limit = 50;
const longest = 100_000;
const hidden = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
const History = Schema.mutable(Schema.Array(Schema.Struct({ text: Schema.String, copied: Schema.Number })));

let history: Entry[] = [];

const save = Effect.fn("Clipboard.save")(function* (next: Entry[]) {
  history = next;
  yield* host.storage.set("history", history);
  yield* host.publish(history);
});

const load = Effect.gen(function* () {
  const stored = yield* host.storage.get("history");
  const entries = yield* Schema.decodeUnknownEffect(History)(stored ?? []).pipe(
    Effect.catch((error) => Effect.as(host.log(`stored history is invalid, starting empty: ${error.message}`), [])),
  );
  yield* save(entries);
});

const record = Effect.fn("Clipboard.record")(function* (change: Gary.ClipboardChange) {
  if (change.access === "never" || !change.types.includes("public.utf8-plain-text")) return;
  if (change.types.some((type) => hidden.includes(type))) return;
  const { text } = yield* host.clipboard.read();
  if (!text?.trim() || text.length > longest) return;
  yield* save([{ text, copied: Date.now() }, ...history.filter((entry) => entry.text !== text)].slice(0, limit));
}, Effect.catch((error) => host.log(`reading the clipboard failed: ${error.message}`)));

const paste = Effect.fn("Clipboard.paste")(function* (text: string) {
  yield* host.clipboard.writeText(text);
  const target = yield* host.paste();
  return target.name ?? "";
});

export default {
  effect: Effect.andThen(load, topic("clipboard").pipe(Stream.runForEach(record))),

  onHotkey(id) {
    if (id === "open") Effect.runSync(host.toggle());
  },

  methods: {
    paste: (text) => Effect.runPromise(paste(text)),
    remove: (text) => Effect.runPromise(save(history.filter((entry) => entry.text !== text))),
  },
} satisfies Gary.Service;

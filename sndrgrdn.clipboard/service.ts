import { Effect, Schema, Stream, host, topic } from "gary:effect";
import type { Content, Entry } from "./topic";

const limit = 50;
const longest = 100_000;
const hidden = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
const History = Schema.mutable(
  Schema.Array(
    Schema.Union([
      Schema.Struct({ text: Schema.String, copied: Schema.Number }),
      Schema.Struct({ image: Schema.String, copied: Schema.Number }),
      Schema.Struct({ files: Schema.mutable(Schema.Array(Schema.String)), copied: Schema.Number }),
    ]),
  ),
);

let history: Entry[] = [];

function same(a: Content, b: Content) {
  if ("text" in a) return "text" in b && a.text === b.text;
  if ("image" in a) return "image" in b && a.image === b.image;
  return "files" in b && a.files.join("\n") === b.files.join("\n");
}

function content({ text, image, files }: Gary.ClipboardContents): Content | null {
  if (files.length) return { files };
  if (text?.trim()) return text.length > longest ? null : { text };
  return image ? { image } : null;
}

const save = Effect.fn("Clipboard.save")(function* (next: Entry[]) {
  history = next;
  yield* host.storage.set("history", history);
  yield* host.publish(history);
});

const load = Effect.gen(function* () {
  const stored = yield* host.storage.get("history");
  const entries = yield* Schema.decodeUnknownEffect(History)(stored ?? []).pipe(
    Effect.catch((error) => Effect.as(host.log(`stored history is invalid, starting empty: ${error.message}`), [])),
  );
  yield* save(entries);
});

const record = Effect.fn("Clipboard.record")(function* (change: Gary.ClipboardChange) {
  if (change.access === "never" || change.types.some((type) => hidden.includes(type))) return;
  const copied = content(yield* host.clipboard.read());
  if (!copied) return;
  yield* save([{ ...copied, copied: Date.now() }, ...history.filter((entry) => !same(entry, copied))].slice(0, limit));
}, Effect.catch((error) => host.log(`reading the clipboard failed: ${error.message}`)));

const paste = Effect.fn("Clipboard.paste")(function* (copied: string) {
  const entry = history.find((each) => String(each.copied) === copied);
  if (!entry) return "";
  if ("files" in entry) yield* host.clipboard.writeFiles(entry.files);
  else if ("image" in entry) yield* host.clipboard.writeImage(entry.image);
  else yield* host.clipboard.writeText(entry.text);
  const target = yield* host.paste();
  return target.name ?? "";
});

export default {
  effect: Effect.andThen(load, topic("clipboard").pipe(Stream.runForEach(record))),

  onHotkey(id) {
    if (id === "open") return host.toggle();
  },

  methods: {
    paste,
    remove: (copied) => save(history.filter((entry) => String(entry.copied) !== copied)),
  },
} satisfies Gary.Service;
